/**
 * Generates src/content/config/allow-lists.generated.ts from the Concept YAMLs.
 *
 * Output: PRICE_BAND_IDS, the allowed Price_Band ids per Concept in ascending band
 * order, for the Pages Functions (task 2.11, Requirements 9.5, 9.14, 14.6).
 *
 * Local file-only script. It reads src/content/concepts/*.yaml and writes one
 * file. It makes no network calls.
 *
 * Run: npx tsx scripts/gen-allow-lists.ts
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';
import { CONCEPT_IDS, type ConceptId } from '../src/content/config/allow-lists';
import { Concept, type ConceptData } from '../src/lib/concept-schema';
import { expectedBandId, validatePriceBands, type BandError } from '../src/lib/price-bands';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const CONCEPTS_DIR = join(ROOT, 'src', 'content', 'concepts');
export const OUTPUT_PATH = join(ROOT, 'src', 'content', 'config', 'allow-lists.generated.ts');

const HEADER = `/**
 * GENERATED FILE. DO NOT EDIT BY HAND.
 *
 * Generated by scripts/gen-allow-lists.ts from src/content/concepts/*.yaml.
 * Regenerate with: npx tsx scripts/gen-allow-lists.ts
 * (npm run build regenerates it too.)
 *
 * PRICE_BAND_IDS lists the Price_Band ids the server accepts for each Concept,
 * in ascending band order (Requirements 9.5, 9.14, 14.6).
 */
`;

function describeBandError(e: BandError): string {
  switch (e.kind) {
    case 'empty_range':
    case 'duplicate_id':
      return `${e.kind} (${e.id})`;
    case 'gap':
    case 'overlap':
    case 'not_ascending':
      return `${e.kind} between ${e.between[0]} and ${e.between[1]}`;
    default:
      return e.kind;
  }
}

/**
 * Pure: turns parsed Concepts into the generated file text. Throws one Error
 * listing every problem (invalid bands, unexpected band ids, missing or
 * duplicate Concepts).
 */
export function renderAllowLists(concepts: readonly ConceptData[]): string {
  const problems: string[] = [];
  const byId = new Map<ConceptId, ConceptData>();

  for (const c of concepts) {
    if (byId.has(c.id)) problems.push(`${c.id}: defined more than once`);
    byId.set(c.id, c);
  }
  for (const id of CONCEPT_IDS) {
    if (!byId.has(id)) problems.push(`${id}: no concept YAML found`);
  }

  const lines: string[] = [];
  for (const id of CONCEPT_IDS) {
    const c = byId.get(id);
    if (!c) continue;
    const errors = validatePriceBands(c.priceBands);
    if (errors.length > 0) {
      problems.push(`${id}: invalid priceBands: ${errors.map(describeBandError).join('; ')}`);
      continue;
    }
    for (const band of c.priceBands) {
      const expected = expectedBandId(id, band);
      if (band.id !== expected) {
        problems.push(`${id}: band id "${band.id}" should be "${expected}"`);
      }
    }
    const ids = c.priceBands.map((b) => JSON.stringify(b.id)).join(', ');
    lines.push(`  ${JSON.stringify(id)}: [${ids}],`);
  }

  if (problems.length > 0) {
    throw new Error(
      `gen-allow-lists: cannot generate PRICE_BAND_IDS:\n${problems.map((p) => `  - ${p}`).join('\n')}`,
    );
  }

  return (
    `${HEADER}\n` +
    `import type { ConceptId } from './allow-lists';\n\n` +
    `export const PRICE_BAND_IDS: Record<ConceptId, readonly string[]> = {\n` +
    `${lines.join('\n')}\n` +
    `};\n`
  );
}

/** Reads and validates the Concept YAMLs (read-only). */
export function readConcepts(dir: string = CONCEPTS_DIR): ConceptData[] {
  const files = readdirSync(dir)
    .filter((f) => f.endsWith('.yaml') || f.endsWith('.yml'))
    .sort();
  return files.map((file) => {
    const parsed = Concept.safeParse(parse(readFileSync(join(dir, file), 'utf8')));
    if (!parsed.success) {
      const detail = parsed.error.issues
        .map((i) => `${i.path.join('.') || '(root)'}: ${i.message}`)
        .join('; ');
      throw new Error(`gen-allow-lists: ${file} fails the Concept schema: ${detail}`);
    }
    return parsed.data;
  });
}

/** Pure with respect to output: reads the YAMLs, returns the file text, writes nothing. */
export function generateAllowLists(dir: string = CONCEPTS_DIR): string {
  return renderAllowLists(readConcepts(dir));
}

function main(): void {
  try {
    writeFileSync(OUTPUT_PATH, generateAllowLists(), 'utf8');
    console.log(`gen-allow-lists: wrote ${OUTPUT_PATH}`);
  } catch (err) {
    console.error(err instanceof Error ? err.message : String(err));
    process.exit(1);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
